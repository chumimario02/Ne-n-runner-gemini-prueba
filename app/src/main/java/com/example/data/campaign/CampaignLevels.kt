        description: String,
        difficulty: LevelDifficulty,
        theme: LevelTheme,
        parTimeMs: Long,
        rawRows: List<String>,
    ): LevelData {
        val width = rawRows.maxOf { it.length }.coerceIn(24, 80)
        val normalized = rawRows.map { row ->
            if (row.length < width) row.padEnd(width, '.') else row.take(width)
        }
        return LevelData(
            id = id,
            title = title,
            description = description,
            authorName = "Neon Core",
            difficulty = difficulty,
            theme = theme,
            width = width,
            height = normalized.size,
            rows = normalized,
            isCampaign = true,
            campaignIndex = index,
            parTimeMs = parTimeMs,
            verified = true,
        )
    }

